"""Generate the Technology and Health Care submission kit from the build.

    python paper/make_submission_kit_thc.py

A kit written by hand is a memory of the last submission, and in this
programme eight statements of one were false, including the name of a file to
upload. So the counts here come from running the build and reading what it
reports, and the page counts from the exported PDFs.

Run it after `build_submission_thc.py` and `check_thc_pages.py`.
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8", errors="replace")

HERE = Path(__file__).resolve().parent
BUILD = HERE / "build"

TEMPLATE = """# Submission kit -- Technology and Health Care (Sage)

**Generated by `paper/make_submission_kit_thc.py` from the build. Do not edit
by hand.**

Journal: Technology and Health Care (Sage, ISSN 0928-7329 / 1878-7401).
Article type: **Original Research Article** -- the only type the journal lists.
Submission site: Sage Track (ScholarOne). Editorial office: thc.pra@sagepub.com.
Editor-in-Chief: Kuan-Ching Li.

## What the journal requires, and where this submission meets it

| Requirement (from the journal's submission guidelines, read 2026-11-05) | This submission |
|---|---|
| Structured abstract of 200 words | **{abstract_words} words**, headed BACKGROUND / OBJECTIVE / METHODS / RESULTS / CONCLUSIONS |
| 4 to 7 keywords | **{keywords} keywords** |
| Statements and Declarations in the article, every heading present | six headings, each present |
| Sage Vancouver references, superscript numerals after the punctuation | **{refs} references** in the article, **{supp_refs}** in the supplement |
| No word limit for an Original Research Article | **{pages} pages** as exported |
| Figures 300 dpi, numbered consecutively, uploaded separately | **{figures} figures** at 600 dpi as `Fig1.png` ... `Fig{figures}.png`, each with 0.5 in of headroom for the portal's label |
| Tables | none; the article's results are in figures and text |
| Review single-anonymized | nothing withheld; no blinded copy |
| Preprints permitted, DOI declared at submission | none posted |

## Files to upload

| Order | File | What it is |
|---|---|---|
| 1 | `paper/build/THC_cover_letter.pdf` | cover letter ({letter_pages} pages) |
| 2 | `paper/build/THC_title_page.docx` | title page with the author's identifying information |
| 3 | `paper/build/THC_manuscript.docx` | the article ({pages} pages as exported) |
| 4 | `paper/build/figures_thc/Fig1.png` ... `Fig{figures}.png` | the figures, one file each |
| 5 | `paper/build/THC_supplementary.docx` | supplementary material ({supp_pages} pages), including the auxiliary uncertainty experiment moved out of the body |

## The release this article reports

**v0.1.1, https://doi.org/10.5281/zenodo.23051189.** The concept identifier
10.5281/zenodo.23034327 resolves to the most recent version and is not what
the article cites. Repository: https://github.com/Institute-of-One/non-ecg-core
(MIT licence).

## What changed since the previous submission

Reviewed by Physics in Medicine and Biology as PMB-122711 and not accepted
(2026-11-04, one referee, five points). Acted on here: the auxiliary
uncertainty experiment and its figure moved to the supplementary material
(referee point 4), which shortened the body by about 900 words (point 5), and
the body is in the first person singular throughout. Not acted on, and said so
in the letter and in the Limitations: the referee's points 1 to 3, the third of
which needs a motion phantom on a real scanner.

## Before pressing submit

1. `python paper/build_submission_thc.py`
2. `python paper/check_thc_submission.py`
3. `python paper/check_thc_pages.py`
4. `python paper/check_references.py` (resolves every DOI again)
5. Open `THC_manuscript.docx` and read it: superscripts after the punctuation,
   no heading at the foot of a page, the declarations under the journal's six
   headings.
6. Open each `Fig*.png` and look at it.
"""


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", type=Path, default=HERE / "SUBMISSION_KIT_THC.md")
    args = ap.parse_args()

    build = subprocess.run([sys.executable, str(HERE / "build_submission_thc.py")],
                           capture_output=True, text=True, encoding="utf-8",
                           errors="replace")
    if build.returncode:
        print(build.stdout[-1500:])
        raise SystemExit("the build failed; the kit is not written from a failed build")
    out = build.stdout

    def grab(pattern: str) -> str:
        m = re.search(pattern, out)
        if not m:
            raise SystemExit("the build did not report %r" % pattern)
        return m.group(1)

    from pypdf import PdfReader

    def pages(name: str) -> int:
        path = BUILD / name
        if not path.is_file():
            raise SystemExit("%s is missing; run check_thc_pages.py first" % name)
        return len(PdfReader(str(path)).pages)

    figures = sorted((BUILD / "figures_thc").glob("Fig*.png"))
    text = TEMPLATE.format(
        abstract_words=grab(r"abstract: (\d+) words"),
        keywords=grab(r"(\d+) keywords"),
        refs=grab(r"body: (\d+) references"),
        supp_refs=grab(r"supplement: (\d+) references"),
        figures=len(figures),
        pages=pages("THC_manuscript.pdf"),
        letter_pages=pages("THC_cover_letter.pdf"),
        supp_pages=pages("THC_supplementary.pdf"))
    args.out.write_text(text, encoding="utf-8", newline="\n")
    print("wrote %s" % args.out)
    print("resolved from the build: %s" % " | ".join(
        line for line in out.splitlines() if line.strip()))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
